// Exercise preserved controls. Client bridges/gamepads here are test doubles, not devices.
const assert = require('node:assert/strict');
module.exports = async (page, showCard, cases) => {
  await page.reload();
  await page.evaluate(() => localStorage.clear());
  for (const side of ['front', 'back']) {
    await showCard(page, cases.image[0][side]);
    await page.keyboard.press('g');
    assert.equal(await page.locator('#popup').isVisible(), true);
    assert.match(await page.locator('#popup').innerText(), /Local personal note/);
    await page.keyboard.press('g');
    assert.equal(await page.locator('#popup').isVisible(), false);
    await page.keyboard.press('j');
    assert.equal(await page.locator('#popup2 img').isVisible(), true);
    await page.keyboard.press('j');
    assert.equal(await page.locator('#popup2').isVisible(), false);
    const before = await page.locator('html').getAttribute('class');
    await page.keyboard.press('c');
    assert.notEqual(await page.locator('html').getAttribute('class'), before);
    await page.keyboard.press('h');
    assert.equal(await page.locator('.linkRender .cloze').isVisible(), true);
    await page.keyboard.press('Control+f');
    assert.equal(await page.locator('#search').evaluate(el => el === document.activeElement), true);
    await page.locator('#search').fill('图片');
    await page.locator('#searchButton').click();
    await page.waitForFunction(() => document.querySelectorAll('mark').length > 0);
    assert.notEqual(await page.locator('#searchResults').innerText(), '0/0');
    await page.locator('#nextMark').click();
    await page.locator('#prevMark').click();
    await page.locator('#clearMarks').click();
    assert.equal(await page.locator('mark').count(), 0);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#searchBox').isVisible(), false);
  }
  for (const side of ['front','back']) {
    await showCard(page, cases.math[0][side]);
    if (side === 'front') await page.keyboard.press(']');
    assert.equal(await page.locator('.cloze math').isVisible(), true);
    assert.equal(await page.locator('.cloze mfrac').count(), 1);
  }
  // Native nonconsecutive ordinals were generated by Anki, not template code.
  await showCard(page, cases.math[1].back);
  assert.match(await page.locator('.cloze').innerText(), /x\^2/);
  await page.evaluate(() => {
    window.testGamepad = {buttons:Array.from({length:16}, () => ({pressed:false,value:0})), axes:[0,0,0,0]};
    Object.defineProperty(navigator,'getGamepads',{configurable:true,value:() => [window.testGamepad]});
    window.testBridgeCommands = [];
    window.pycmd = command => window.testBridgeCommands.push(command);
  });
  const press = async index => {
    await page.evaluate(index => { testGamepad.buttons[index] = {pressed:true,value:1}; }, index);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.evaluate(index => { testGamepad.buttons[index] = {pressed:false,value:0}; }, index);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  };
  await showCard(page, cases.overview[0].front);
  await press(5);
  assert.equal(await page.locator('.cloze-placeholder').count(), 0);
  await press(4);
  assert.equal(await page.locator('.cloze-placeholder').count(), 1);
  await press(1);
  await page.waitForFunction(() => testBridgeCommands.includes('ans'));
  for (const [button,ease] of [[0,1],[1,3],[2,2],[3,4]]) {
    await showCard(page, cases.overview[0].back);
    await press(button);
    await page.waitForFunction(ease => testBridgeCommands.includes('ease'+ease), ease);
  }
  // Removed cards must no longer intercept keyboard commands.
  await showCard(page, '<section>Unrelated card</section>');
  assert.equal(await page.evaluate(() => document.dispatchEvent(new KeyboardEvent('keydown', {code:'KeyC',bubbles:true,cancelable:true}))), true);
  await page.reload();
};
